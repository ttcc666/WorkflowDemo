import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { spawnSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = fileURLToPath(new URL('../../', import.meta.url))
const generated = join(root, 'output/engineering/contracts-generated')
const update = process.argv.includes('--update')
const args = ['run', '--project', 'eng/Approval.ContractTool', '--configuration', 'Release']
if (process.argv.includes('--no-build')) args.push('--no-build')
args.push('--', '--output', generated)
const run = spawnSync('dotnet', args, { cwd: root, stdio: 'inherit' })
if (run.error) throw run.error
if (run.status !== 0) process.exit(run.status ?? 1)

const files = ['approval.openapi.json', 'flow.schema.json', 'form.schema.json', 'Approval.Core.api.txt', 'Approval.AspNetCore.api.txt', 'Approval.Certificate.api.txt', 'Certificate.Api.forwards.txt']
const doc = JSON.parse(await readFile(join(generated, files[0]), 'utf8'))
for (const entity of ['ApprovalInstance', 'ApprovalDefinition', 'ApprovalTask', 'ApprovalLog', 'ApprovalMessage', 'ApprovalOutboxMessage', 'ApprovalDraft', 'ApprovalFile', 'CertificateEntity', 'CertificateRequest']) {
  if (doc.components?.schemas?.[entity]) throw new Error(`Persistence entity leaked into the HTTP contract: ${entity}`)
}
for (const path of ['/api/approval/instances/{id}', '/api/approval/definitions/{key}', '/api/approval/forms/{key}/start', '/api/certificates']) {
  if (!doc.paths[path]) throw new Error(`The generated document is missing ${path}.`)
}
for (const [path, methods] of Object.entries(doc.paths)) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!['get', 'post', 'put', 'delete'].includes(method)) continue
    const success = Object.entries(operation.responses ?? {}).filter(([status]) => /^2\d\d$/.test(status))
    if (!success.length) throw new Error(`Missing success response: ${method} ${path}`)
    for (const [status, response] of success) {
      if (status === '204' || (method === 'get' && path === '/api/approval/files/{id}')) continue
      if (!response.content?.['application/json']?.schema) throw new Error(`Missing response schema: ${method} ${path}`)
    }
  }
}

const drift = []
async function verify(path, contents) {
  contents = contents.replaceAll('\r\n', '\n')
  if (update) {
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, contents)
    return
  }
  const existing = await readFile(path, 'utf8').catch(error => error.code === 'ENOENT' ? null : Promise.reject(error))
  if (existing?.replaceAll('\r\n', '\n') !== contents) drift.push(path)
}

await mkdir(join(root, 'contracts'), { recursive: true })
for (const file of files) await verify(join(root, 'contracts', file), await readFile(join(generated, file), 'utf8'))
const types = '/** Generated by pnpm contracts:update. Do not edit directly. */\n' + astToString(await openapiTS(doc, { alphabetize: true }))
await verify(join(root, 'web/packages/approval-ui/src/contracts/http.generated.ts'), types)
if (drift.length) throw new Error('Contract drift detected. Review and run pnpm contracts:update:\n' + drift.join('\n'))
console.log(update ? 'Updated API, JSON schemas, public API baselines and TypeScript contracts.' : 'Contract generation matches all checked-in baselines.')
